const locales: Record<string, MessageMap> = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

const LOCALE_KEY = 'meteorx_locale'

export const AVAILABLE_LOCALES = Object.keys(locales)

// 纯 DOM 应用逻辑，不依赖 Pinia，供首屏引导与 store 变更复用。
export function applyLocaleToDOM(locale: string) {
  document.documentElement.setAttribute('lang', locale)
}

// 从 localStorage 读取持久化语言，回退中文（无 Pinia 依赖，供挂载前引导调用）。
export function readStoredLocale(): string {
  const stored = localStorage.getItem(LOCALE_KEY)
  return stored && locales[stored] ? stored : 'zh-CN'
}

export const useI18nStore = defineStore('i18n', () => {
  // 全局唯一语言源，跨组件共享。
  const locale = ref<string>(readStoredLocale())

  function t(key: string, ...args: (string | number)[]): string {
    const messages = locales[locale.value] || zhCN
    let text = messages[key] || key
    args.forEach((arg, i) => {
      text = text.replace(`{${i}}`, String(arg))
    })
    return text
  }

  function setLocale(next: string) {
    if (locales[next]) {
      locale.value = next
      localStorage.setItem(LOCALE_KEY, next)
      applyLocaleToDOM(next)
    }
  }

  return { locale, t, setLocale, availableLocales: AVAILABLE_LOCALES }
})
